-- 3. PL/SQL 

-- Procedure for driver transfer 
CREATE OR REPLACE PROCEDURE transfer_driver(
    p_driver_number IN NUMBER,
    p_new_team_name IN VARCHAR2
) AS
    v_new_team_id NUMBER;
BEGIN
    -- Find new team ID
    SELECT id_team INTO v_new_team_id 
    FROM constructors 
    WHERE name = p_new_team_name;

    -- Update driver
    UPDATE drivers 
    SET id_team = v_new_team_id 
    WHERE driver_number = p_driver_number;

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Success: Driver is' || p_driver_number || ' transferred.');

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Error team is not found.');
    WHEN OTHERS THEN
        ROLLBACK;
        DBMS_OUTPUT.PUT_LINE('Error while transfer.');
END;
