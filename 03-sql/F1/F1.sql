-- 1. TABLE CREATION 

-- Teams table 
CREATE TABLE constructors (
    id_team NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(50) NOT NULL UNIQUE,
    principal VARCHAR2(50),
    base_city VARCHAR2(50),
    budget_cap NUMBER(15, 2) CHECK (budget_cap > 0) -- Budget need to be positive
);

-- Drivers table
CREATE TABLE drivers (
    id_driver NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(50) NOT NULL,
    driver_number NUMBER UNIQUE CHECK (driver_number > 0 AND driver_number < 100), -- cant be more then 100
    country VARCHAR2(3),
    id_team NUMBER,
    CONSTRAINT fk_team FOREIGN KEY (id_team) 
        REFERENCES constructors(id_team) 
        ON DELETE SET NULL -- if team gone driver has no team
);

-- Races table 
CREATE TABLE races (
    id_race NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gp_name VARCHAR2(100) NOT NULL,
    circuit VARCHAR2(100),
    race_date DATE DEFAULT SYSDATE,
    laps NUMBER CHECK (laps > 0)
);

-- Race results 
CREATE TABLE race_results (
    id_result NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_race NUMBER NOT NULL REFERENCES races(id_race) ON DELETE CASCADE,
    id_driver NUMBER NOT NULL REFERENCES drivers(id_driver) ON DELETE CASCADE,
    position NUMBER CHECK (position BETWEEN 1 AND 20),
    points NUMBER(4,1) DEFAULT 0.0,
    fastest_lap CHAR(1) DEFAULT 'N' CHECK (fastest_lap IN ('Y', 'N')), -- Y has the fastest lap
    UNIQUE(id_race, id_driver) -- driver can complete race once
);

